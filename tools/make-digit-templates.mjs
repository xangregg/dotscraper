// Writes src/core/digit-templates.js: the shape of each digit in the fonts figures are set in, for labels.js to tell
// digits apart by. The shapes are drawn by a browser (tools/digit-fonts.html, opened here in headless Chrome
// through tools/check-page.mjs), so no template comes from a test image: the label benchmark
// (tools/label-bench.mjs) measures the reader on figures it has not seen.
//
// The fonts are those of the machine this runs on (macOS's, as committed); the page names any it lacks.
//
// Usage: node tools/make-digit-templates.mjs [url]   (the server must be running: npm run serve)

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TEMPLATE_WIDTH, TEMPLATE_HEIGHT } from '../src/core/digit-templates.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LEVELS = 15; // a cell is written as one hex digit

const url = process.argv[2] ?? 'http://localhost:8003/tools/digit-fonts.html';
const out = execFileSync('node', [join(ROOT, 'tools/check-page.mjs'), url, '--until', 'window.digitFonts', '--eval', 'JSON.stringify(window.digitFonts)'], { encoding: 'utf8', maxBuffer: 1 << 26 });
const line = out.split('\n').find(l => l.startsWith('eval: '));
if (!line)
    throw new Error(`no result from ${url}:\n${out}`);
const { fonts, missing } = JSON.parse(JSON.parse(line.slice('eval: '.length)));
const rows = grid => Array.from({ length: TEMPLATE_HEIGHT }, (_, j) => grid.slice(j * TEMPLATE_WIDTH, (j + 1) * TEMPLATE_WIDTH).map(v => Math.round(LEVELS * Math.min(1, Math.max(0, v))).toString(16)).join('')).join(' ');
const blocks = fonts.map(({ name, digits }) => `    '${name}': {\n${Object.entries(digits).map(([d, grid]) => `        ${d}: '${rows(grid)}',`).join('\n')}\n    },`);
writeFileSync(join(ROOT, 'src/core/digit-templates.js'), `// Generated by tools/make-digit-templates.mjs: do not edit.
//
// The shape of each digit in ${fonts.length} fonts, for labels.js: how dark each cell of a ${TEMPLATE_WIDTH} × ${TEMPLATE_HEIGHT} grid is when the digit
// is scaled to the grid's height and centered, the mean over sizes and places on the pixel grid as a browser draws
// it (tools/digit-fonts.html).

export const TEMPLATE_WIDTH = ${TEMPLATE_WIDTH};
export const TEMPLATE_HEIGHT = ${TEMPLATE_HEIGHT};

// a digit's rows from the top, a hex digit per cell: 0 is the page, f the ink
const FONTS = {
${blocks.join('\n')}
};

/** @type {{name: string, digits: Object<string, Float32Array>}[]}  digits: row-major, 0–1 */
export const DIGIT_TEMPLATES = Object.entries(FONTS).map(([name, digits]) => ({
    name,
    digits: Object.fromEntries(Object.entries(digits).map(([d, cells]) => [d, Float32Array.from(cells.replace(/ /g, ''), cell => parseInt(cell, 16) / ${LEVELS})])),
}));
`);
console.log(`${fonts.length} fonts: ${fonts.map(f => f.name).join(', ')}`);
if (missing.length)
    console.log(`not on this machine, left out: ${missing.join(', ')}`);
